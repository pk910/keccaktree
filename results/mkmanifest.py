#!/usr/bin/env python3
"""results/manifest.txt for the integrated tree: mkmanifest.py <repo> <gensha.txt> <axioms dir>"""
import hashlib, os, re, subprocess, sys
repo, gensha, axdir = sys.argv[1:4]
git = lambda *a: subprocess.run(['git', '-C', repo] + list(a), capture_output=True, text=True, check=True).stdout.strip()
sha = lambda p: hashlib.sha256(open(os.path.join(repo, p), 'rb').read()).hexdigest()
gens = {}
for l in open(gensha):
    d, n, h = l.split()
    gens.setdefault(d.split('/')[0], []).append((d.split('/')[1], n, h))
ax = {}
for f in sorted(os.listdir(axdir)):
    txt = open(os.path.join(axdir, f)).read()
    for m in re.finditer(r"'([^']+)' depends on axioms: \[(.*?)\]", txt, re.S):
        names = [x.strip() for x in m.group(2).split(',')]
        std = [x for x in names if x in ('propext', 'Classical.choice', 'Quot.sound')]
        cert = [x for x in names if '._native.bv_decide.ax_' in x]
        bad = [x for x in names if x not in std and x not in cert]
        ax[m.group(1)] = '%s + %d bv_decide certificates%s' % (', '.join(std), len(cert), ('; OTHER: ' + ', '.join(bad)) if bad else '')
    for m in re.finditer(r"'([^']+)' does not depend on any axioms", txt):
        ax[m.group(1)] = 'none'
KN = 'Keccaktree.Kernels.'
K = [  # (kernel, isa, Ns, program Ns, object, theorems)
    ('scalar_x1', 'AArch64', 'ScalarX1', 'ScalarX1', 'scalar_x1', ['ScalarX1.All.scalar_x1_all', 'ScalarX1.All.norm_thm', 'ScalarX1.All.kernel', 'ScalarX1.All.lib']),
    ('sha3_x2', 'AArch64', 'Sha3X2', 'Sha3X2', 'sha3_x2', ['Sha3X2.All.' + t for t in ('all', 'norm_thm', 'kernel', 'lib')]),
    ('neon_x2', 'AArch64', 'NeonX2', 'NeonX2', 'neon_x2', ['NeonX2.All.' + t for t in ('all', 'norm_thm', 'kernel', 'lib')]),
    ('sha3_x3', 'AArch64', 'Sha3X3', 'Sha3X3', 'sha3_x3', ['Sha3X3.All.' + t for t in ('all', 'norm_thm', 'kernel')]),
    ('sha3_x3r', 'AArch64', 'Sha3X3r', 'Sha3X3r', 'sha3_x3r', ['Sha3X3r.All.' + t for t in ('all', 'norm_thm', 'kernel')]),
    ('neon_x3', 'AArch64', 'NeonX3', 'NeonX3', 'neon_x3', ['NeonX3.All.' + t for t in ('all', 'norm_thm', 'kernel')]),
    ('x86_x1', 'x86-64', 'X86X1', 'X86X1', 'x86_x1', ['X86X1.All.x86_x1_all', 'X86X1.Lib.norm_thm', 'X86X1.Lib.kernel', 'X86X1.Lib.lib_x86_x1']),
    ('rv64_x1', 'RISC-V', 'Rv64X1', 'Rv64X1', 'rv64_x1', ['Rv64X1.All.' + t for t in ('rv64_x1_all', 'norm_thm', 'kernel', 'norm_thm_ch', 'kernel_ch')]),
    ('zbb_x1', 'RISC-V', 'ZbbX1', 'ZbbX1', 'zbb_x1', ['ZbbX1.All.' + t for t in ('zbb_x1_all', 'norm_thm', 'kernel', 'norm_thm_ch', 'kernel_ch')]),
] + [(f'{k}_v{V}', f'RISC-V VLEN {64 * V}', f'{ns}V{V}', ns, k, [f'{ns}V{V}.All.' + t for t in ('all', 'all_ch', 'norm_thm', 'norm_thm_ch', 'kernel', 'kernel_ch')])
     for (k, ns) in (('rvv', 'Rvv'), ('rvv_zvkb', 'RvvZvkb')) for V in (2, 4, 8)]
LIBS = [('AArch64 library', 'Kernels/ArmLib.lean', ['ArmLib.lib_arm_all']),
        ('RISC-V library VLEN 128', 'Kernels/RvLib2.lean', ['RvLib.lib2', 'RvLib.lib2ch']),
        ('RISC-V library VLEN 256', 'Kernels/RvLib4.lean', ['RvLib.lib4', 'RvLib.lib4ch']),
        ('RISC-V library VLEN 512', 'Kernels/RvLib8.lean', ['RvLib.lib8', 'RvLib.lib8ch'])]
head = git('rev-parse', '--short', 'HEAD')
src_tree = git('rev-parse', 'HEAD:src')
src_last = git('log', '-1', '--format=%h', '--', 'src')
out = []
w = out.append
w('# keccaktree Lean verification: manifest of the proved kernels (integrated tree)')
w('# regenerate: python3 results/mkmanifest.py . results/gen_sha256.txt <dir of #print axioms outputs>')
w(f'# tree: branch integrate {head}; src/ tree {src_tree} (last src/ commit {src_last}; identical to origin/main src/)')
w('# program  : lean/Keccaktree/Kernels/<P>/Program.lean, sha256 and last commit (generated by lean/asm2lean.py from the object file)')
w('# object   : the kernel object assembled from src/keccak256_<k>.S (+ its .inc) at the src/ tree above; last commit of the .S')
w('# gen      : generated proof dirs (not committed), <dir> <files> <sha256> with')
w('#            sha256 = tar --sort=name --mtime=@0 --owner=0 --group=0 --numeric-owner --mode=a=r,u+w,a+X --format=gnu -cf - <Ns>/<Gen> | sha256sum')
w('#            run in lean/Keccaktree/Kernels (script: /root/kt-int-gensha.sh <lean dir> <Ns...>)')
w('# axioms   : #print axioms on the merged core (lake build in /root/kt-int): the standard axioms + the number of')
w('#            bv_decide certificate axioms (`<decl>._native.bv_decide.ax_*`); anything else is listed as OTHER')
w('')
for (k, isa, ns, pns, obj, thms) in K:
    pp = f'lean/Keccaktree/Kernels/{pns}/Program.lean'
    w(f'[{k}] {isa}')
    w(f'  program   {pp} sha256 {sha(pp)} commit {git("log", "-1", "--format=%h", "--", pp)}')
    w(f'  object    keccak256_{obj}.o from src/keccak256_{obj}.S commit {git("log", "-1", "--format=%h", "--", f"src/keccak256_{obj}.S")}')
    ap = f'lean/Keccaktree/Kernels/{ns}/All.lean'
    w(f'  all       {ap} sha256 {sha(ap)}')
    for (g, n, h) in gens.get(ns, []):
        w(f'  gen       {ns}/{g} {n} {h}')
    for t in thms:
        w(f'  theorem   {KN}{t}')
        w(f'    axioms  {ax.get(KN + t, "NOT CHECKED (integrated build in progress)")}')
    w('')
for (name, p, thms) in LIBS:
    w(f'[{name}] lean/Keccaktree/{p} sha256 {sha("lean/Keccaktree/" + p)}')
    for t in thms:
        w(f'  theorem   {KN}{t}')
        w(f'    axioms  {ax.get(KN + t, "NOT CHECKED (integrated build in progress)")}')
    w('')
IP = [('scalar_x1', 'ScalarX1', 'lib_inplace_scalar_x1'), ('sha3_x2', 'Sha3X2', 'lib_inplace_sha3_x2'),
      ('neon_x2', 'NeonX2', 'lib_inplace_neon_x2'), ('sha3_x3', 'Sha3X3', None), ('sha3_x3r', 'Sha3X3r', None),
      ('neon_x3', 'NeonX3', None), ('x86_x1', 'X86X1', 'lib_inplace_x86_x1'), ('rv64_x1', 'Rv64X1', 'lib_inplace_rv64_x1')]
for (k, ns, lib) in IP:
    ap = f'lean/Keccaktree/Kernels/{ns}/InPlaceAll.lean'
    w(f'[in place: {k}] {ap} sha256 {sha(ap)}')
    d = os.path.join(repo, f'lean/Keccaktree/Kernels/{ns}/InPlace')
    for f in sorted(os.listdir(d)):
        w(f'  summary   {ns}/InPlace/{f} sha256 {sha(os.path.join("lean/Keccaktree/Kernels", ns, "InPlace", f))}')
    for t in [f'{ns}.InPlaceAll.access_thm'] + ([f'{ns}.InPlaceAll.{lib}'] if lib else []):
        w(f'  theorem   {KN}{t}')
        w(f'    axioms  {ax.get(KN + t, "NOT CHECKED (integrated build in progress)")}')
    w('')
w('[in place: AArch64 library] lean/Keccaktree/Kernels/ArmLibInPlace.lean sha256 ' + sha('lean/Keccaktree/Kernels/ArmLibInPlace.lean'))
w(f'  theorem   {KN}ArmLibInPlace.lib_inplace_arm_all')
w(f'    axioms  {ax.get(KN + "ArmLibInPlace.lib_inplace_arm_all", "NOT CHECKED (integrated build in progress)")}')
w('')
w('[core] lean/Keccaktree/Asm/LibTable.lean, lean/Keccaktree/Dispatch.lean')
for t in ('Keccaktree.Asm.LibTable.lib_x86', 'Keccaktree.Asm.LibTable.lib_arm', 'Keccaktree.Asm.LibTable.lib_rv',
          'Keccaktree.Dispatch.hash_x86', 'Keccaktree.Dispatch.hash_x86_reachable', 'Keccaktree.Dispatch.hash_arm', 'Keccaktree.Dispatch.hash_rv'):
    w(f'  theorem   {t}')
    w(f'    axioms  {ax.get(t, "NOT CHECKED (integrated build in progress)")}')
open(os.path.join(repo, 'results', 'manifest.txt'), 'w').write('\n'.join(out) + '\n')
