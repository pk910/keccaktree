#!/usr/bin/env bash
# Regenerates the committed AArch64 assembly kernels in src/asm/ from the
# intrinsics/C sources, like tools/gen_x86_asm.sh does for x86-64. Each .S
# holds an ELF (Linux) and a Mach-O (macOS, x18 reserved) body.
#
# Usage: tools/gen_arm_asm.sh   (needs clang; output recorded with its version)
set -euo pipefail
cd "$(dirname "$0")/../src"
CLANG=${CLANG:-clang}
COMMON="-O3 -ffreestanding -fno-asynchronous-unwind-tables -fno-exceptions -fno-stack-protector -fno-ident -fomit-frame-pointer -I."

gen() { # out.S src.c flags...
	local out="$1" src="$2"; shift 2
	local elf macho
	elf=$($CLANG --target=aarch64-linux-gnu -fPIC $COMMON "$@" -S -o - "$src")
	macho=$($CLANG --target=arm64-apple-macos11 $COMMON "$@" -S -o - "$src")
	clean() { grep -vE '^\s*\.(file|addrsig|addrsig_sym|ident|build_version)\b|^\s*(//|;)' ; }
	{
		echo "/* GENERATED by tools/gen_arm_asm.sh from $src $* - do not edit."
		echo " * $($CLANG --version | head -1) */"
		case "$*" in *+sha3*) echo ".arch armv8.2-a+sha3" ;; esac
		echo "#if defined(__APPLE__)"
		echo "$macho" | clean
		echo "#elif defined(__ELF__)"
		echo "$elf" | clean
		echo '.section .note.GNU-stack,"",@progbits'
		echo "#else"
		echo "#error unsupported AArch64 object format"
		echo "#endif"
	} > "asm/$out"
}

SHA3="-march=armv8.2-a+sha3 -DKT_SHA3"
gen keccak256_neon_x2.S keccak256_neon_x2.c
gen keccak256_sha3_x2.S keccak256_neon_x2.c $SHA3
hyb() { # name sha3? hv hs [extra flags]
	local name=$1 flags=""; [ "$2" = 1 ] && flags="$SHA3"
	gen keccak256_$name.S keccak256_hybrid_arm.c $flags -DKT_HV=$3 -DKT_HS=$4 ${5:-} -DFN=keccaktree_keccak256_$name
}
hyb scalar_x1 0 0 1
hyb sha3_x3 1 1 1
