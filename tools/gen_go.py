#!/usr/bin/env python3
"""Emit keccak256_1_generic.go: the pure-Go fallback, translated from the same
specialised permutation that tools/gen_core.py emits for the C backends."""
import io
import re
import sys

sys.path.insert(0, __import__('os').path.dirname(__file__))
from gen_core import emit  # noqa: E402

RC = [0x0000000000000001, 0x0000000000008082, 0x800000000000808a, 0x8000000080008000,
      0x000000000000808b, 0x0000000080000001, 0x8000000080008081, 0x8000000000008009,
      0x000000000000008a, 0x0000000000000088, 0x0000000080008009, 0x000000008000000a,
      0x000000008000808b, 0x800000000000008b, 0x8000000000008089, 0x8000000000008003,
      0x8000000000008002, 0x8000000000000080, 0x000000000000800a, 0x800000008000000a,
      0x8000000080008081, 0x8000000000008080, 0x0000000080000001, 0x8000000080008008]

TOK = re.compile(r'\s*([A-Za-z_][A-Za-z0-9_]*|0x[0-9A-Fa-f]+ULL|\d+|[(),])')


def parse(s):
    toks = TOK.findall(s)
    pos = [0]

    def expr():
        t = toks[pos[0]]; pos[0] += 1
        if pos[0] < len(toks) and toks[pos[0]] == '(':
            pos[0] += 1
            args = []
            while True:
                args.append(expr())
                t2 = toks[pos[0]]; pos[0] += 1
                if t2 == ')':
                    break
            return go(t, args)
        if t.endswith('ULL'):
            return t[:-3]
        return t
    return expr()


def go(f, a):
    if f == 'XOR':
        return '(%s ^ %s)' % (a[0], a[1])
    if f == 'XOR3':
        return '(%s ^ %s ^ %s)' % tuple(a)
    if f == 'ROL':
        return 'bits.RotateLeft64(%s, %s)' % (a[0], a[1])
    if f == 'ROL1XOR':
        return '(%s ^ bits.RotateLeft64(%s, 1))' % (a[0], a[1])
    if f == 'XORROL':
        return 'bits.RotateLeft64(%s^%s, %s)' % (a[0], a[1], a[2])
    if f == 'CHI':
        return '(%s ^ (%s &^ %s))' % (a[0], a[2], a[1])
    if f == 'KC':
        return 'uint64(%s)' % a[0]
    if f == 'IOTA':
        return '(%s ^ 0x%016x)' % (a[0], RC[int(a[1])])
    raise ValueError(f)


def main():
    buf = io.StringIO()
    emit(buf)
    out = sys.stdout
    out.write('''// Code generated by tools/gen_go.py; DO NOT EDIT.

package keccaktree

import (
\t"encoding/binary"
\t"math/bits"
)

// keccak256_1_generic is the pure-Go fallback: digests[i] = keccak256(chunks[2i] || chunks[2i+1]).
// It is the same single-block, fully unrolled permutation as the C backends.
func keccak256_1_generic(digests [][32]byte, chunks [][32]byte) {
\tfor i := 0; i+1 < len(chunks); i += 2 {
\t\tl, r := &chunks[i], &chunks[i+1]
\t\ta0, a1 := binary.LittleEndian.Uint64(l[0:]), binary.LittleEndian.Uint64(l[8:])
\t\ta2, a3 := binary.LittleEndian.Uint64(l[16:]), binary.LittleEndian.Uint64(l[24:])
\t\ta4, a5 := binary.LittleEndian.Uint64(r[0:]), binary.LittleEndian.Uint64(r[8:])
\t\ta6, a7 := binary.LittleEndian.Uint64(r[16:]), binary.LittleEndian.Uint64(r[24:])
\t\tvar o0, o1, o2, o3 uint64
''')
    for line in buf.getvalue().splitlines():
        line = line.strip()
        if line.startswith('/*'):
            out.write('\t\t// %s\n' % line[2:-2].strip())
            continue
        decl = line.startswith('V ')
        if decl:
            line = line[2:]
        name, rhs = line.rstrip(';').split(' = ', 1)
        out.write('\t\t%s %s %s\n' % (name, ':=' if decl else '=', parse(rhs)))
    out.write('''\t\td := &digests[i/2]
\t\tbinary.LittleEndian.PutUint64(d[0:], o0)
\t\tbinary.LittleEndian.PutUint64(d[8:], o1)
\t\tbinary.LittleEndian.PutUint64(d[16:], o2)
\t\tbinary.LittleEndian.PutUint64(d[24:], o3)
\t}
}
''')


if __name__ == '__main__':
    main()
