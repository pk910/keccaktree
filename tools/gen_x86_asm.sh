#!/usr/bin/env bash
# Regenerates the committed x86-64 assembly kernels in src/asm/ from the
# intrinsics sources. The assembly is what the library builds from, so the
# result no longer depends on the C compiler doing a good job (gcc's output
# for these kernels is about 10% slower than clang's). Each .S holds an ELF
# (Linux) and a COFF (Windows x64 ABI) body.
#
# Usage: tools/gen_x86_asm.sh   (needs clang; output recorded with its version)
set -euo pipefail
cd "$(dirname "$0")/../src"
CLANG=${CLANG:-clang}
COMMON="-O3 -fno-asynchronous-unwind-tables -fno-exceptions -fno-stack-protector -fno-ident -fomit-frame-pointer -I."

gen() { # out.S src.c flags...
	local out="$1" src="$2"; shift 2
	local elf coff
	elf=$($CLANG --target=x86_64-linux-gnu -fPIC $COMMON "$@" -S -o - "$src")
	coff=$($CLANG --target=x86_64-w64-windows-gnu $COMMON "$@" -S -o - "$src")
	clean() { grep -vE '^\s*\.(file|addrsig|addrsig_sym|ident)\b|^\s*#' ; }
	{
		echo "/* GENERATED by tools/gen_x86_asm.sh from $src $* - do not edit."
		echo " * $($CLANG --version | head -1) */"
		echo "#if defined(__ELF__)"
		echo "$elf" | clean
		echo "#elif defined(_WIN64)"
		echo "$coff" | clean
		echo "#else"
		echo "#error unsupported x86-64 object format"
		echo "#endif"
		echo "#if defined(__ELF__)"
		echo '.section .note.GNU-stack,"",@progbits'
		echo "#endif"
	} > "asm/$out"
}

gen keccak256_avx512_x8.S keccak256_avx512_x8.c -mavx512f -mavx512vl
gen keccak256_avx512vl_x4.S keccak256_avx2_x4.c -DKT_AVX512VL -mavx2 -mavx512f -mavx512vl
gen keccak256_avx2_x4.S keccak256_avx2_x4.c -mavx2
