#!/usr/bin/env python3
"""Generate the fully unrolled Keccak-f[1600] core specialised for
keccak256 over a single 64-byte input (one Merkle node = two 32-byte chunks).

The emitted code is backend-agnostic: it only uses the type `V` and the
macros below, which every backend defines before including the file.

  XOR(a,b)       a ^ b
  XOR3(a,b,c)    a ^ b ^ c
  ROL(a,n)       rotate each 64-bit lane left by n (1..63)
  ROL1XOR(a,b)   a ^ rotl(b,1)                (theta D column)
  XORROL(a,b,n)  rotl(a ^ b, n)               (theta add fused with rho)
  CHI(a,b,c)     a ^ (~b & c)
  With --ternlog (for AVX-512 vpternlogq / ARMv8.2 EOR3) theta's add is
  emitted as XOR3(A, C[x-1], rotl(C[x+1],1)) per lane instead of A ^ D[x].

  KC(x)          broadcast 64-bit constant x
  IOTA(a,i)      a ^ RC[i]

Input:  V a0..a7   (the 8 little-endian 64-bit words of the 64-byte node)
Output: V o0..o3   (the 4 words of the 32-byte digest)

Specialisations (vs. a generic sponge):
  * absorb is free: state lanes 0..7 = input, lane 8 = 0x01 (Keccak pad),
    lane 16 = 0x8000000000000000 (final pad bit at byte 135 of the 136-byte
    rate); all other lanes are zero, so round 0's theta parity drops ~15 XORs.
  * the last round only computes the 4 output lanes (row y=0, x=0..3).
"""
import sys

RHO = [0, 1, 62, 28, 27, 36, 44, 6, 55, 20, 3, 10, 43, 25, 39,
       41, 45, 15, 21, 8, 18, 2, 61, 56, 14]

def emit(out, ternlog=False, vp='', mp='', typ='V', rounds=None):
    """vp prefixes variable names, mp prefixes macro names (so a second,
    differently typed stream can share a function), typ is the lane type.
    With rounds=[] each round's lines are appended to it as a list instead of
    being written to out (used by tools/gen_hybrid.py to interleave streams)."""
    cur = []
    def w(line):
        if rounds is None:
            out.write(line)
        else:
            cur.append(line)
    # state: list of expressions/variable names, None = known zero
    st = ['%sa%d' % (vp, i) for i in range(8)] + [None] * 17
    st[8] = mp + 'KC(0x0000000000000001ULL)'
    st[16] = mp + 'KC(0x8000000000000000ULL)'
    for r in range(24):
        last = (r == 23)
        if rounds is not None and r:
            rounds.append(cur); cur = []
        w('    /* round %d */\n' % r)
        p = '%sr%d_' % (vp, r)
        # theta parity
        for x in range(5):
            terms = [st[x + 5 * y] for y in range(5) if st[x + 5 * y] is not None]
            expr = terms[0]
            rest = terms[1:]
            while rest:
                if len(rest) >= 2:
                    expr = mp + 'XOR3(%s, %s, %s)' % (expr, rest[0], rest[1]); rest = rest[2:]
                else:
                    expr = mp + 'XOR(%s, %s)' % (expr, rest[0]); rest = rest[1:]
            w('    %s %sc%d = %s;\n' % (typ, p, x, expr))
        need_d = (not ternlog) or any(v is None for v in st)
        for x in range(5):
            if need_d:
                w('    %s %sd%d = %sROL1XOR(%sc%d, %sc%d);\n' % (typ, p, x, mp, p, (x + 4) % 5, p, (x + 1) % 5))
        if ternlog:
            # theta add fused into one 3-input XOR per lane: A ^ C[x-1] ^ rotl(C[x+1],1)
            for x in range(5):
                w('    %s %se%d = %sROL(%sc%d, 1);\n' % (typ, p, x, mp, p, x))
        rows = [0] if last else range(5)
        nst = [None] * 25
        for Y in rows:
            b = []
            for X in range(5):
                xs = (3 * Y + X) % 5   # source column
                ys = X                 # source row
                i = xs + 5 * ys
                d = '%sd%d' % (p, xs)
                rot = RHO[i]
                src = st[i]
                if src is None:
                    e = (mp + 'ROL(%s, %d)' % (d, rot)) if rot else d
                elif ternlog:
                    x3 = mp + 'XOR3(%s, %sc%d, %se%d)' % (src, p, (xs + 4) % 5, p, (xs + 1) % 5)
                    e = (mp + 'ROL(%s, %d)' % (x3, rot)) if rot else x3
                else:
                    e = (mp + 'XORROL(%s, %s, %d)' % (src, d, rot)) if rot else mp + 'XOR(%s, %s)' % (src, d)
                bn = '%sb%d_%d' % (p, Y, X)
                w('    %s %s = %s;\n' % (typ, bn, e))
                b.append(bn)
            xr = range(4) if last else range(5)
            for X in xr:
                nn = ('%so%d' % (vp, X)) if last else ('%ss%d_%d' % (vp, r, X + 5 * Y))
                e = mp + 'CHI(%s, %s, %s)' % (b[X], b[(X + 1) % 5], b[(X + 2) % 5])
                if X == 0 and Y == 0:
                    e = mp + 'IOTA(%s, %d)' % (e, r)
                if last:
                    w('    %s = %s;\n' % (nn, e))
                else:
                    w('    %s %s = %s;\n' % (typ, nn, e))
                nst[X + 5 * Y] = nn
        st = nst
    if rounds is not None:
        rounds.append(cur)

if __name__ == '__main__':
    o = sys.stdout
    tl = '--ternlog' in sys.argv
    o.write('/* GENERATED by tools/gen_core.py%s - do not edit. */\n' % (' --ternlog' if tl else ''))
    emit(o, tl)
