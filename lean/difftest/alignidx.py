#!/usr/bin/env python3
"""Emit Tools/AlignIdx.lean: per x86 kernel, the instruction indices of aligned vector moves
(vmovdqa / vmovdqa64 with a memory operand), from the real translator's view of the object.
    alignidx.py <kobj dir>"""
import os
import re
import sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
import asm2lean  # noqa: E402

kdir = sys.argv[1]
out = ['/-! GENERATED by difftest/alignidx.py: aligned vector moves of the x86 kernels. -/', '',
       'def alignedIdx : List (String × List Nat) := [']
rows = []
for p in sorted(os.listdir(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'Keccaktree', 'Kernels'))):
    prog = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'Keccaktree', 'Kernels', p, 'Program.lean')
    if not os.path.exists(prog):
        continue
    head = open(prog).read(400)
    if 'Asm.X86' not in head.split('\n')[0]:
        continue
    obj = re.search(r'(keccak256_[a-z0-9_]+\.o)', head).group(1)
    t = asm2lean.X86(os.path.join(kdir, obj), 'keccaktree_' + obj[:-2])
    idx = [i for i, x in enumerate(t.texts) if x.split()[0] in ('vmovdqa', 'vmovdqa64') and '[' in x]
    rows.append('  ("%s", [%s])' % (p, ', '.join(map(str, idx))))
out.append(',\n'.join(rows))
out.append(']\n')
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'Tools', 'AlignIdx.lean'), 'w').write('\n'.join(out))
print(len(rows), 'kernels')
