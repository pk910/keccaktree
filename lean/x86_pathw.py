#!/usr/bin/env python3
"""Emit `Gen<seg>/PathW.lean` for every generated segment of a kernel: each slice never loads word 112
of the constant image (`pathW`, kernel-checked), hence the segment runs the same under every value of
that word (`run_agree`, `factsV v : SegFacts (setWord rodata 112 v) prog`).

    x86_pathw.py <Dir> [word=112]
"""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))


def main():
    d = sys.argv[1]
    w = int(sys.argv[2]) if len(sys.argv) > 2 else 112
    kdir = os.path.join(HERE, f'Keccaktree/Kernels/{d}')
    for g in sorted(os.listdir(kdir)):
        if not g.startswith('Gen') or not os.path.exists(os.path.join(kdir, g, 'Seg.lean')):
            continue
        seg = open(os.path.join(kdir, g, 'Seg.lean')).read()
        K = len(re.findall(r'^def cert(\d+) ', seg, re.M))
        rdx = 'theorem facts_rdx' in seg
        L = [f"""import Keccaktree.Kernels.{d}.{g}.Seg
import Keccaktree.Asm.X86Thresh
set_option linter.unusedSectionVars false
set_option linter.unusedVariables false
/-! GENERATED by lean/x86_pathw.py; do not edit.  The segment never loads word {w} of the constant image. -/
namespace Keccaktree.Kernels.{d}.{g}
open Keccaktree.Asm Keccaktree.Asm.X86 Keccaktree.Asm.X86K
open Keccaktree.Kernels.{d} (prog rodata)
"""]
        for c in range(K):
            L.append(f"""set_option maxRecDepth 100000 in
theorem pathW{c} : pathW rodata prog {w} (cert{c}).idx (cutOf (cert{c}).ctl (cert{c}).sc) = true := by decide +kernel
""")
        lens = ' + '.join(f'(cert{c}).idx.length' for c in range(K))
        steps = ''.join(f"  have s{c} := (cert{c}).step ρ hρ hw {'S0' if c == 0 else f'(segAt{c} S0)'} "
                        f"{'hc' if c == 0 else f's{c - 1}.2.2.2'} {'hs' if c == 0 else f's{c - 1}.2.2.1'}\n" for c in range(K))
        rws = ', '.join(
            f"SliceCert.run_agree (cert{c}) hr pathW{c} ρ hρ hw {'S0' if c == 0 else f'(segAt{c} S0)'} "
            f"{'hc' if c == 0 else f's{c - 1}.2.2.2'} {'hs' if c == 0 else f's{c - 1}.2.2.1'}, s{c}.1, "
            f"show X86.isa.execTrace rodata (cert{c}).slice {'S0' if c == 0 else f'(segAt{c} S0)'} = segAt{c + 1} S0 from rfl"
            for c in range(K))
        L.append(f"""set_option maxRecDepth 100000 in
set_option maxHeartbeats 40000000 in
/-- The segment runs the same under every image that differs from `rodata` only in word {w}. -/
theorem run_agree (r2 : Array (BitVec 64)) (hr : AgreeExcept rodata r2 {w}) (ρ : Reloc) (hρ : ρ.ok) (hw : ρ.within B)
    (S0 : State (BitVec 64)) (hc : relocState ρ (cutOf ctl0 sc0) = cutOf ctl0 S0) (hs : SliceCert.Ok S0) :
    X86.isa.run r2 prog segLen S0 = X86.isa.run rodata prog segLen S0 := by
{steps}  show X86.isa.run r2 prog ({lens}) S0 = X86.isa.run rodata prog ({lens}) S0
  repeat rw [Isa.run_add]
  rw [{rws}]

set_option maxRecDepth 100000 in
/-- The segment under the image with word {w} set to `v`. -/
def factsV (v : Nat) : X86K.SegFacts (setWord rodata {w} v) prog where
  ctl0 := facts.ctl0
  sc0 := facts.sc0
  ctlK := facts.ctlK
  scK := facts.scK
  len := facts.len
  wok := facts.wok
  run := fun ρ hρ hw S0 hc hs => by
    rw [show facts.len = segLen from rfl, run_agree _ (agree_setWord rodata {w} v) ρ hρ hw S0 hc hs]
    exact facts.run ρ hρ hw S0 hc hs
  frame := fun ρ hρ hw S0 hc hs r q hq => by
    rw [show facts.len = segLen from rfl, run_agree _ (agree_setWord rodata {w} v) ρ hρ hw S0 hc hs]
    exact facts.frame ρ hρ hw S0 hc hs r q hq
""")
        for fld in ('ctl0', 'sc0', 'ctlK', 'scK', 'len', 'wok'):
            L.append(f"theorem factsV_{fld} (v : Nat) : (factsV v).{fld} = facts.{fld} := rfl\n")
        if rdx:
            L.append(f"""set_option maxRecDepth 100000 in
theorem factsV_rdx (v : Nat) (ρ : Reloc) (hρ : ρ.ok) (hw : ρ.within B) (S0 : State (BitVec 64))
    (hc : relocState ρ (cutOf ctl0 sc0) = cutOf ctl0 S0) (hs : SliceCert.Ok S0) :
    envOf (X86.isa.run (setWord rodata {w} v) prog segLen S0) 258 = envOf S0 258 := by
  rw [run_agree _ (agree_setWord rodata {w} v) ρ hρ hw S0 hc hs]
  exact facts_rdx ρ hρ hw S0 hc hs
""")
        L.append(f"end Keccaktree.Kernels.{d}.{g}\n")
        open(os.path.join(kdir, g, 'PathW.lean'), 'w').write('\n'.join(L))
        print(g, K)


if __name__ == '__main__':
    main()
