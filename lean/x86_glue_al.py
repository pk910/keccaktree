HERE = os.environ.get('KT_ROOT') or os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import x86_all as X

BIG = 10 ** 6
SYM = lambda k: f'keccaktree_keccak256_{k}'


class Val:
    """a register value along count steps: Lean expression + Python value (None: symbolic) + a representative
    value deciding the branches of a symbolic path"""
    def __init__(self, lean, py, rep=None):
        self.lean, self.py = lean, py
        self.rep = py if rep is None else rep


def fixed_of(ch):
    """the count registers with literal values (closed: decidable hand-over checks)"""
    items = [f'({r}, {lit(v.py)})' for r, v in sorted(ch.vals.items()) if v.py is not None]
    return '[' + ', '.join(items) + ']'


def lit(v):
    return f'({v} : Int)' if v >= 0 else f'(({v}) : Int)'


class FrChain:
    """emit a chain of count steps: `have f<i> := ...`"""
    def __init__(self, prog, rodata, name, out, indent):
        self.prog, self.rodata, self.f, self.out, self.ind = prog, rodata, name, out, indent
        self.i = 0
        self.vals = {}     # reg -> Val
        self.zf = self.cf = None
        self.flags_known = False
        self.pc = None
        self.steps = 0

    def cur(self):
        if getattr(self, 'f0', None) and self.i == 0:
            return self.f0
        return f'{self.f}{self.i}'

    def emit(self, s):
        self.out.append(' ' * self.ind + s)

    def nxt(self, expr):
        self.i += 1
        self.emit(f'have {self.cur()} := {expr}')
        self.steps += 1

    def mem(self):
        return '(by simp [setVal])'

    def bound(self):
        return 'fr_lo', 'fr_hi'

    def step(self):
        """one count step at self.pc; returns ('ok'|'tail', info)"""
        pc = self.pc
        op, a = X.parse(self.prog[pc])
        hi = f'(by decide +kernel : prog.getD {pc} .nop = {self.prog[pc]})'
        p = self.cur()
        V = self.vals
        if op == 'cmpi':
            v = V[a[0]]
            self.nxt(f'{p}.cmpi {a[0]} ({a[1]}) {v.lean} {hi} {self.mem()} (by fr_lo) (by fr_hi)')
            self.zf_lean = f'{v.lean} = {a[1]}'
            self.zf, self.cf = v.rep == a[1], v.rep < a[1]
            self.flags_known = v.py is not None
            self.pc = pc + 1
        elif op == 'test':
            v = V[a[0]]
            self.nxt(f'{p}.test {a[0]} {v.lean} {hi} {self.mem()} (by fr_lo) (by fr_hi)')
            self.zf, self.cf = v.rep == 0, False
            self.flags_known = v.py is not None
            self.pc = pc + 1
        elif op == 'sub':
            v = V[a[0]]
            self.nxt(f'{p}.sub {a[0]} (by decide) ({a[1]}) {v.lean} {hi} {self.mem()} (by fr_lo) (by fr_hi)')
            self.zf_lean = f'{v.lean} = {a[1]}'
            self.zf, self.cf = v.rep == a[1], v.rep < a[1]
            self.flags_known = v.py is not None
            V[a[0]] = Val(f'({v.lean} - {a[1]})', None if v.py is None else v.py - a[1], v.rep - a[1])
            self.pc = pc + 1
        elif op == 'movi':
            self.nxt(f'{p}.movi {a[0]} (by decide) ({a[1]}) {hi}')
            V[a[0]] = Val(lit(a[1]), a[1])
            self.pc = pc + 1
        elif op == 'mov':
            v = V[a[1]]
            self.nxt(f'{p}.mov {a[0]} {a[1]} (by decide) {v.lean} {hi} {self.mem()}')
            V[a[0]] = v
            self.pc = pc + 1
        elif op == 'xorz':
            self.nxt(f'{p}.xorz {a[0]} (by decide) {hi}')
            V[a[0]] = Val('(0 : Int)', 0)
            self.zf, self.cf = True, False
            self.flags_known = True
            self.pc = pc + 1
        elif op == 'bt':
            w, v = V[a[0]], V[a[1]]
            self.nxt(f'{p}.bt {a[0]} {a[1]} {w.lean} {v.lean} {hi} {self.mem()} {self.mem()} (by fr_lo) (by fr_hi)')
            self.cf = bool((w.rep % 2 ** 64 >> (v.rep % 64)) & 1)
            self.pc = pc + 1
        elif op == 'cmprm':
            v = V[a[0]]
            off = int(re.search(r'\d+', a[1]).group(0))
            wv = self.rodata[off // 8]
            self.nxt(f'{p}.cmprm {a[0]} {off} {v.lean} {hi} (by decide) (by decide) {self.mem()} (by fr_lo) (by fr_hi)')
            self.zf_lean = f'BitVec.ofInt 64 {v.lean} = rodata.getD (({off} : Int) / 8).toNat 0'
            self.zf, self.cf = v.rep == wv, v.rep < wv
            self.flags_known = v.py is not None
            self.pc = pc + 1
        elif op in ('nop', 'vzeroupper'):
            self.nxt(f'{p}.nop (Or.{"inl" if op == "nop" else "inr"} {hi})')
            self.pc = pc + 1
        elif op == 'jmp':
            self.nxt(f'{p}.jmp {a[0]} {hi}')
            self.pc = a[0]
        elif op == 'jcc':
            taken = self.decide(a[0])
            tgt = a[1] if taken else pc + 1
            self.nxt(f'({p}.jcc .{a[0]} {a[1]} {hi}).pc_congr (pc\' := {tgt}) (by rw [{"if_pos" if taken else "if_neg"} (by fr_cond)])')
            self.pc = tgt
        elif op == 'jcct':
            taken = self.decide(a[0])
            if taken:
                return 'tail', (a[0], a[1], hi)
            self.nxt(f'{p}.jcct_not .{a[0]} "{a[1]}" {hi} (by fr_cond)')
            self.pc = pc + 1
        else:
            raise AssertionError(('not a count step', pc, self.prog[pc]))
        return 'ok', None

    def decide(self, c):
        assert self.zf is not None and self.cf is not None, (self.pc, c, self.zf, self.cf)
        return X.cond(c, self.zf, self.cf)



def sc_gd(seg_path, idx):
    """the general registers (gd) of the closed state `sc<idx>` in a generated Seg.lean / Slice file"""
    txt = open(seg_path).read()
    m = re.search(rf'^def sc{idx} : State \(BitVec 64\) := (.*)$', txt, re.M)
    gds = re.findall(r'#v\[((?:0x[0-9a-f]+#64, )*0x[0-9a-f]+#64)\]', m.group(1))
    return [int(x.split('#')[0], 16) for x in gds[0].split(', ')]


def sc_pc(seg_path, idx):
    """the pc of the closed state `sc<idx>`"""
    txt = open(seg_path).read()
    m = re.search(rf'^def sc{idx} : State \(BitVec 64\) := (.*)$', txt, re.M)
    mm = re.search(r'\(memLit \[.*?\]\) (\d+) (\d+) (?:true|false) (?:true|false) ', m.group(1))
    return int(mm.group(1))


def ptr_off(word):
    return word & 0x00ffffffffffffff




def seg_acc(G, m, hw, S, hcut, hok, b, bf):
    """the access condition of segment `G` at relocation `rho m` from its footprint summaries"""
    return (f'seg_acc {G}.facts InPlace.{G}.certs InPlace.{G}.len InPlace.{G}.chain (by hd_tac InPlace.{G}.certs) '
            f'({m}) {hw} {S} {hcut} {hok} ({b}) ({bf})\n        (by sum_tac InPlace.{G}.sums)')


def thresh_al(t, d, names, segs, nslices):
    """the access proof for every value `v` of the threshold word 112 (`setWord rodata 112 v`, as
    `x86_glue.py`'s `thresh_transform`): runs under the image, segments by `seg_accV` (summaries of the
    default image, slices that never load word 112: `PathW`)"""
    W = '(setWord rodata 112 v)'
    t = t.replace(f'namespace Keccaktree.Kernels.{d}.InPlaceAll', f'namespace Keccaktree.Kernels.{d}.InPlaceAllV')
    t = t.replace(f'import Keccaktree.Kernels.{d}.Lib\n', f'import Keccaktree.Kernels.{d}.LibV\n' +
                  ''.join(f'import Keccaktree.Kernels.{d}.Gen{n}.PathW\n' for n in names))
    t = t.replace('import Keccaktree.Asm.X86AccFr', 'import Keccaktree.Asm.X86AccThresh')
    t = t.replace(f'open Keccaktree.Kernels.{d}.All\n', f'open Keccaktree.Kernels.{d}.AllV\n')
    t = t.replace('abbrev DoneAK := DoneA rodata prog', f'abbrev DoneAK (v : Nat) := DoneA {W} prog')
    t = t.replace('DoneAK off', 'DoneAK v off')
    t = t.replace('(rodata := rodata)', f'(rodata := {W})')
    t = t.replace(' rodata prog', f' {W} prog')
    # segments: the access condition under the image
    t = re.sub(r'seg_acc (Gen\w+)\.facts ', r'seg_accV (agree_setWord rodata 112 v) \1.facts ', t)
    t = re.sub(r'\(by hd_tac InPlace\.(Gen\w+)\.certs\)', r'(by hd_tac InPlace.\1.certs) (pw_\1)', t)
    out_ = []
    for ln in t.split('\n'):
        m = re.match(r'^(\s*)obtain ⟨(\w+), (\w+)⟩ := (Gen\w+)\.facts\.run (.*)$', ln)
        if m:
            ind_, a_, b_, g_, rest_ = m.groups()
            out_.append(f'{ind_}obtain ⟨{a_}, {b_}⟩ := ({g_}.factsV v).run {rest_}')
            out_.append(f'{ind_}simp only [{g_}.factsV_ctlK, {g_}.factsV_scK, {g_}.factsV_len] at {a_} {b_}')
            continue
        m = re.match(r"^(\s*)have ([\w']+) := (.*)\.seg('?) (Gen\w+)\.facts (.*)\(by wok_out (Gen\w+)\.facts\)$", ln)
        if m:
            ind_, h_, base_, pr_, g_, rest_, g2_ = m.groups()
            out_.append(f'{ind_}have {h_} := {base_}.seg{pr_} ({g_}.factsV v) {rest_}(by wok_out2 {g_}.factsV {g_}.facts)')
            out_.append(f'{ind_}simp only [{g_}.factsV_len] at {h_}')
            continue
        out_.append(ln)
    t = '\n'.join(out_)
    t = re.sub(r'(Gen\w+)\.facts_rdx', r'\1.factsV_rdx v', t)
    for nm in ['exitA_\\w+', 'bodyA_\\w+', 'body_\\w+', 'afterBA_step', 'afterBA', 'afterPA_\\w+']:
        t = re.sub(rf'theorem ({nm}) \(', r'theorem \1 (v : Nat) (hv64 : v < 2 ^ 64) (', t)
        t = re.sub(rf'(?<![\w.])({nm}) off ', r'\1 v hv64 off ', t)
    t = t.replace('theorem access_thm :', 'theorem access_thm (v : Nat) (hv64 : v < 2 ^ 64) :')
    # the slices of each segment never load word 112
    pw = ''
    for n in names:
        G = f'Gen{n}'
        k = nslices[n]
        pw += (f'theorem pw_{G} : ∀ C ∈ InPlace.{G}.certs, pathW rodata prog 112 C.idx (cutOf C.ctl C.sc) = true := by\n'
               f'  intro C hC\n  simp only [InPlace.{G}.certs, List.mem_cons, List.mem_nil_iff, or_false] at hC\n'
               f'  rcases hC with {" | ".join(["rfl"] * k)}\n'
               f'  exacts [{", ".join(f"{G}.pathW{i}" for i in range(k))}]\n\n')
    t = t.replace('abbrev DoneAK (v : Nat)', pw + 'abbrev DoneAK (v : Nat)')
    return t + '\n'


def main():
    # `--out <dir>`: write InPlaceAll(V).lean into <dir> instead of the kernel's directory
    outdir = None
    if '--out' in sys.argv:
        i = sys.argv.index('--out')
        outdir = sys.argv[i + 1]
        del sys.argv[i:i + 2]
