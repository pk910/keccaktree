#!/usr/bin/env python3
"""In place (`out == in`): emit `Keccaktree/Kernels/<Dir>/InPlaceAll.lean`, the access theorem
(`LibAlias.AccessThm`) of an x86 kernel whose every-count proof was generated by `x86_glue.py`
(agent x86b), and the kernel of the in-place library (`kernelAl`).

    x86_glue_al.py <kernel>

Run in a workspace with the kernel's generated segments (`Gen*/Seg.lean`), its `All.lean`/`Lib.lean`
(from `x86_glue.py`), `x86_all.py`, `plans/<kernel>_all.json`, and the segments' footprint summaries
(`gen_inplace.py <Dir> Gen... --eval --split` -> `InPlace/Gen*.lean`).  Forked from `x86_glue.py`:
the same control-flow skeleton, with the access condition in place of the outcome:

  * `exitA_<X>`  : exit segment `X` (`chain_access` on its summaries, `seg_acc`), then `ret`/tail call
                   (`acc_one`); the final bound is the output end of the nodes done, and a tail call's
                   hand-over entry fixes those nodes (`Hand.tail`);
  * `bodyA_<z>`  : one loop iteration (segments `Ba<z>`, `Bb`): bound `4(off+done)` -> `+4N`;
  * `afterBA_step`, `afterBA`, `afterPA_<P>` : the dispatch of `x86_glue.py` with `FrA` count steps
                   (same instruction lemmas, plus their access condition) and `DoneA` in place of `Done`;
                   the state facts (cuts, `Inv`) come from `All.body_<z>`;
  * `access_thm` : from the entry;  `kernelAl` : `mkKernelAnnAl` (AVX-512, x86b's annotation) or
                   `mkKernelAl` (the prefix route) with `All.norm_thm` and `access_thm`.

The proof files of the kernel (`All.lean`, `Lib.lean`, segments) are only read.
"""
