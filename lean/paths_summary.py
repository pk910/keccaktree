#!/usr/bin/env python3
"""notes/paths.md from lean/paths/*.json (see analyze_paths.py)."""
import json, glob, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ORDER = ['x86_x1', 'avx2_x2', 'avx2_x4', 'avx2_x5', 'avx2_x6', 'avx2_x8', 'avx2_x9', 'avx2_x10', 'avx512vl_x4', 'avx512vl_x4d',
         'avx512_x8', 'avx512_x8d', 'avx512_x9', 'avx512_x9d', 'scalar_x1', 'sha3_x2', 'neon_x2', 'sha3_x3', 'sha3_x3r', 'neon_x3',
         'rv64_x1', 'zbb_x1', 'rvv_v2', 'rvv_v4', 'rvv_v8', 'rvv_zvkb_v2', 'rvv_zvkb_v4', 'rvv_zvkb_v8']
VARIANTS = sorted(os.path.basename(p)[:-5] for p in glob.glob(os.path.join(HERE, 'paths', '*_*max*.json')))
short = lambda s: s.replace('keccaktree_keccak256_', '') if s else s

def ranges(cs):
    cs = sorted(cs)
    if len(cs) <= 4:
        return ', '.join(map(str, cs))
    steps = {b - a for a, b in zip(cs, cs[1:])}
    if len(steps) == 1:
        return f'{cs[0]}..{cs[-1]} step {steps.pop()}'
    out, run = [], [cs[0]]
    for c in cs[1:]:
        if c == run[-1] + 1: run.append(c)
        else: out.append(run); run = [c]
    out.append(run)
    return ', '.join(f'{r[0]}..{r[-1]}' if len(r) > 2 else ', '.join(map(str, r)) for r in out)

lines = ['# Code-path inventory of the kernels', '',
         'Generated by `lean/paths_summary.py` from `lean/paths/<kernel>.json` (produced by `lean/analyze_paths.py` from',
         '`kttool paths <kernel> <64 + 2*NODES> 400000 0`: the concrete model run from `initState` on the test message for',
         'every count `0 .. 64 + 2*NODES`).  Model: the object code of branch `paths` (= `lean-verification` + PR #17).', '',
         '* **classes**: counts whose executed instruction paths coincide up to the number of iterations of the outer',
         '  loop (the loop head is the instruction whose visits cut the path of the largest count into the longest',
         '  repeated piece: the batch call / batch body).',
         '* **count readers**: forward taint from the count register (x86 `rdx`, AArch64 `x2`, RISC-V `a2`) through',
         '  registers, flags and stack cells (named by abstract base + offset); `address` = a count-derived value used',
         '  only as a memory base, `vl` = the RVV vector length.',
         '* **batch**: x86 — the batch subroutine (`.call` target to its `.ret`); AArch64/RISC-V — the loop body.',
         '* every count of every kernel gives the right digests for the nodes it hashes itself, never errs, and every',
         '  tail call hands over `input + 64·done`, `output + 32·done` and the remaining count (`handover`).', '']
summary = ['| kernel | NODES | counts | classes | tail calls (counts) | count-dependent branches | batch reads count | failing |',
           '|---|---|---|---|---|---|---|---|']
details = []
for k in ORDER + VARIANTS:
    p = os.path.join(HERE, 'paths', f'{k}.json')
    if not os.path.exists(p): continue
    d = json.load(open(p))
    tails = {}
    for e in d['per_count']:
        if e['tail']: tails.setdefault(short(e['tail']), []).append(e['count'])
    br = d['batch_count_readers']
    kinds = set()
    for r in br:
        t = r['instruction']
        if 'vl' in r['reads']: kinds.add('vl')
        elif 'address' in r['reads']: kinds.add('pointer select')
        elif t.startswith(('.storeq', '.str', '.sd')): kinds.add('spill')
        elif t.startswith(('.loadq', '.ldr', '.ld')): kinds.add('fill')
        else: kinds.add('loop control')
    bad = d['failing_counts'] + d['inconsistent_handovers']
    summary.append(f"| {k} | {d['nodes']} | {d['count_range'][0]}..{d['count_range'][1]} | {len(d['classes'])} | "
                   + ('; '.join(f'{t}: {ranges(c)}' for t, c in tails.items()) or '—')
                   + f" | {len(d['count_dependent_branches'])} | {', '.join(sorted(kinds)) or 'no'} | {bad or 'none'} |")
    details += [f"## {k}", '',
                f"NODES {d['nodes']} ({d['isa']}); outer loop head: instruction {d['loop_head']['index'] if d['loop_head'] else '—'}"
                f" `{d['loop_head']['instruction'] if d['loop_head'] else ''}`; batch region: {d['batch_region']['kind']}"
                f" {d['batch_region']['start']}..{d['batch_region']['end']} ({d['batch_region']['instructions']} instructions).", '',
                '| class | counts | loop iterations | entry / body variants / exit (instructions) | tail |', '|---|---|---|---|---|']
    for c in d['classes']:
        its = sorted(set(c['iterations'].values()))
        details.append(f"| {c['id']} | {ranges(c['counts'])} | {ranges(its)} | {c['entry_len']} / {c['body_variants'] or '—'} / {c['exit_len']} | {short(c['tail']) or '—'} |")
    details += ['', 'Count-dependent branches: ' + ', '.join(f"{b['index']} `{b['instruction']}`" for b in d['count_dependent_branches']), '']
    if br:
        details.append('Count readers in the batch: ' + ', '.join(f"{r['index']} `{r['instruction']}` ({'/'.join(r['reads'])})" for r in br[:12])
                       + (f' … ({len(br)} in all, {d["batch_count_vl_readers"]} only through `vl`)' if len(br) > 12 else ''))
    else:
        details.append('The batch never reads the count.')
    details.append('')
open(os.path.join(HERE, '..', 'notes', 'paths.md'), 'w').write('\n'.join(lines + summary + [''] + details) + '\n')
print('\n'.join(summary))
