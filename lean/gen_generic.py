#!/usr/bin/env python3
"""Generate lean/Keccaktree/Generic.lean: the portable kernels (src/keccak256_generic.c and
keccak256_1_generic.go) as Lean programs, transcribed statement by statement from the sources
(the round macro, the Go round 0 / loop body / round 23), with the reassigned temporaries
renamed into single-assignment form."""
import re, sys, os

HERE = os.path.dirname(os.path.abspath(__file__))
C = open(os.path.join(HERE, '..', 'src', 'keccak256_generic.c')).read()
GO = open(os.path.join(HERE, '..', 'keccak256_1_generic.go')).read()


def expr(e, env):
    """a C/Go expression over the renamed temporaries, as Lean"""
    e = e.strip()
    e = re.sub(r'bits\.RotateLeft64\(', 'ROL(', e)
    e = re.sub(r'keccakRC\[rc\]', 'rc', e)
    e = re.sub(r'\(rc\)', 'rc', e)
    e = re.sub(r'0x([0-9a-fA-F]+)(ULL)?', lambda m: '0x%s#64' % m.group(1), e)
    e = re.sub(r'\bA##(\d+)', lambda m: 'a[%s]' % m.group(1), e)
    e = re.sub(r'\bE##(\d+)', lambda m: 'e%s' % m.group(1), e)
    # ROL(x, n) -> ROL (x) n
    while 'ROL(' in e:
        i = e.index('ROL(')
        depth, j = 0, i + 3
        for j in range(i + 3, len(e)):
            if e[j] == '(':
                depth += 1
            elif e[j] == ')':
                depth -= 1
                if depth == 0:
                    break
        inner = e[i + 4:j]
        k = inner.rfind(',')
        e = e[:i] + '(ROL (' + inner[:k].strip() + ') ' + inner[k + 1:].strip() + ')' + e[j + 1:]
    e = e.replace('^', '^^^').replace('|', '|||').replace('&', '&&&')
    e = re.sub(r'(?<![\w\]])~', '~~~', e)   # unary not (C)
    e = re.sub(r'(^|[\s(])\^\^\^(?=\w|\()', r'\1~~~', e)  # unary not (Go `^x`), after the binary rewrite
    # variables -> their current SSA names
    e = re.sub(r'\b([A-Z]\d*)\b', lambda m: env.get(m.group(1), m.group(1)), e)
    return e


def ssa(stmts, env, out, prefix):
    """emit `let` lines for `X = expr;` statements, renaming reassigned temporaries"""
    counts = {}
    for st in stmts:
        m = re.match(r'^\s*([A-Z]+##?\d*|[A-Z]\d*)\s*=\s*(.*?);?\s*$', st)
        if not m:
            continue
        lhs, rhs = m.group(1), m.group(2)
        rhs = expr(rhs, env)
        name = lhs.replace('##', '')
        if name[0] in 'AE' and name[1:].isdigit():   # an output lane (never read again in its block)
            lean = 'e' + name[1:]
        else:
            counts[name] = counts.get(name, 0) + 1
            lean = '%s%s_%d' % (prefix, name.lower(), counts[name])
        env[name] = lean
        out.append('  let %s := %s' % (lean, rhs))


def c_macro():
    i = C.index('#define KECCAK_ROUND(A, E, rc)')
    j = C.index('} while (0)', i)
    body = C[i:j]
    lines = [re.sub(r'\\$', '', ln).strip() for ln in body.splitlines()]
    lines = [ln for ln in lines if ln and not ln.startswith('#define') and not ln.startswith('do') and not ln.startswith('/*')]
    return lines


def go_block(start_marker, end_marker):
    i = GO.index(start_marker)
    j = GO.index(end_marker, i)
    return [ln.strip() for ln in GO[i:j].splitlines() if '=' in ln and not ln.strip().startswith('//')]


out = []
out.append('''/-!
# The portable keccaktree kernels, as Lean programs

GENERATED by `lean/gen_generic.py` from `src/keccak256_generic.c` and
`keccak256_1_generic.go`; do not edit.  Every assignment of the sources is a
`let` (reassigned temporaries get numbered names); `ROL` is the C macro;
`Lanes` is the 25-lane state `A0..A24` / `E0..E24` (lane `i = x + 5y`).
Both kernels keep lanes 1, 2, 8, 12, 17 and 20 inverted (lane complementing).
Nothing here refers to the specification; `Keccaktree/Proof.lean` proves
that these programs compute keccak256.
-/

namespace Keccaktree.Generic

abbrev W := BitVec 64
abbrev Lanes := Vector W 25

/-- `static const uint64_t RC[24]` / `keccakRC` -/
def RC (r : Nat) : W :=
  match r with
''')
rc = re.search(r'RC\[24\] = \{(.*?)\};', C, re.S).group(1)
rcs = re.findall(r'0x([0-9a-fA-F]{16})ULL', rc)
assert len(rcs) == 24
for k, v in enumerate(rcs):
    out.append('  | %-2d => 0x%s#64' % (k, v))
out.append('  | _  => 0#64\n')
out.append('/-- `#define ROL(a, n) (((a) << (n)) | ((a) >> (64 - (n))))` -/')
out.append('def ROL (a : W) (n : Nat) : W := (a <<< n) ||| (a >>> (64 - n))\n')

# ---- C round macro
out.append('/-- `KECCAK_ROUND(A, E, rc)`: the 25 lanes `E0..E24` from `A0..A24` (`src/keccak256_generic.c`). -/')
out.append('def roundC (a : Lanes) (rc : W) : Lanes :=')
body = []
ssa(c_macro(), {}, body, 'c')
out += body
out.append('  #v[' + ', '.join('e%d' % k for k in range(25)) + ']\n')

# ---- C absorb
out.append('''/-- `ld64` (little-endian bytes `p off .. p (off+7)`). -/
def ld64 (p : Nat → BitVec 8) (off : Nat) : W :=
  (p off).zeroExtend 64 ||| ((p (off + 1)).zeroExtend 64 <<< 8) ||| ((p (off + 2)).zeroExtend 64 <<< 16) |||
  ((p (off + 3)).zeroExtend 64 <<< 24) ||| ((p (off + 4)).zeroExtend 64 <<< 32) ||| ((p (off + 5)).zeroExtend 64 <<< 40) |||
  ((p (off + 6)).zeroExtend 64 <<< 48) ||| ((p (off + 7)).zeroExtend 64 <<< 56)

/-- `st64`: byte `i` is `(unsigned char)(v >> (8 * i))`. -/
def st64 (v : W) (i : Nat) : BitVec 8 := (v >>> (8 * i)).truncate 8

/-- The absorb of `keccak256_node`: the data lanes (1 and 2 inverted), the padding and the
constant lanes of the complemented zero state. -/
def absorbC (input : Nat → BitVec 8) : Lanes :=
  #v[ld64 input 0, ~~~ld64 input 8, ~~~ld64 input 16, ld64 input 24,
     ld64 input 32, ld64 input 40, ld64 input 48, ld64 input 56,
     ~~~0x0000000000000001#64, 0, 0, 0, ~~~0#64, 0, 0, 0,
     0x8000000000000000#64, ~~~0#64, 0, 0, ~~~0#64, 0, 0, 0, 0]

/-- `for (int r = 1; r < 23; r += 2) { KECCAK_ROUND(E, A, RC[r]); KECCAK_ROUND(A, E, RC[r + 1]); }`:
`loopC r e k` runs the remaining `k` iterations from round `r` on the state `e`. -/
def loopC (r : Nat) (e : Lanes) : Nat → Lanes
  | 0 => e
  | k + 1 => loopC (r + 2) (roundC (roundC e (RC r)) (RC (r + 1))) k

/-- `keccak256_node(output, input)`: the 32 digest bytes of the 64-byte node. -/
def nodeC (input : Nat → BitVec 8) : Vector (BitVec 8) 32 :=
  let a := absorbC input
  let e := roundC a (RC 0)
  let e := loopC 1 e 11
  let a := roundC e (RC 23)
  Vector.ofFn fun j : Fin 32 =>
    match j.val / 8 with
    | 0 => st64 a[0] (j.val % 8)
    | 1 => st64 (~~~a[1]) (j.val % 8)
    | 2 => st64 (~~~a[2]) (j.val % 8)
    | _ => st64 a[3] (j.val % 8)

/-- `keccaktree_keccak256_generic(output, input, count)`: digest `k` (for `k < count`) is the
hash of the node at `input + 64 k`. -/
def hashC (input : Nat → BitVec 8) (k : Nat) : Vector (BitVec 8) 32 :=
  nodeC fun i => input (64 * k + i)
''')

# ---- Go
out.append('''/-! ## The Go kernel (`keccak256_1_generic.go`) -/

/-- The absorb: `chunks[2i]` (lanes 0..3, 1 and 2 inverted) and `chunks[2i+1]` (lanes 4..7). -/
def absorbGo (l r : Nat → BitVec 8) : Vector W 8 :=
  #v[ld64 l 0, ~~~ld64 l 8, ~~~ld64 l 16, ld64 l 24, ld64 r 0, ld64 r 8, ld64 r 16, ld64 r 24]
''')
# round 0 (hand-folded) from the 8 data lanes
out.append('/-- Round 0 as written in the Go source: on the sparse initial state (the 8 data lanes `a`). -/')
out.append('def round0Go (a : Vector W 8) : Lanes :=')
body = []
env = {'A%d' % k: 'a[%d]' % k for k in range(8)}
ssa(go_block('// round 0 (sparse state', '// rounds 1..22'), env, body, 'g')
out += body
out.append('  #v[' + ', '.join('e%d' % k for k in range(25)) + ']\n')
# loop body: E -> A with keccakRC[rc], then A -> E with keccakRC[rc+1]
loop = go_block('for rc := 1; rc < 23; rc += 2 {', '// round 23')
# split at the second theta (the first statement reading A0 again)
split = [i for i, ln in enumerate(loop) if ln.startswith('C0 = A0')][0]
out.append('/-- The first half of the Go loop body: lanes `A0..A24` from `E0..E24` with `keccakRC[rc]`. -/')
out.append('def roundGoEA (e : Lanes) (rc : W) : Lanes :=')
body = []
env = {'E%d' % k: 'e[%d]' % k for k in range(25)}
stmts = [ln.replace('keccakRC[rc]', 'rc') for ln in loop[:split]]
# A_k are outputs here: rename them as outputs
stmts = stmts
ssa(stmts, env, body, 'h')
out += body
out.append('  #v[' + ', '.join('e%d' % k for k in range(25)) + ']\n')
out.append('/-- The second half of the Go loop body: `E0..E24` from `A0..A24` with `keccakRC[rc+1]`. -/')
out.append('def roundGoAE (a : Lanes) (rc : W) : Lanes :=')
body = []
env = {'A%d' % k: 'a[%d]' % k for k in range(25)}
stmts = [ln.replace('keccakRC[rc+1]', 'rc') for ln in loop[split:]]
ssa(stmts, env, body, 'i')
out += body
out.append('  #v[' + ', '.join('e%d' % k for k in range(25)) + ']\n')
out.append('''/-- `for rc := 1; rc < 23; rc += 2 { ... }` -/
def loopGo (rc : Nat) (e : Lanes) : Nat → Lanes
  | 0 => e
  | k + 1 => loopGo (rc + 2) (roundGoAE (roundGoEA e (RC rc)) (RC (rc + 1))) k
''')
# round 23: only lanes A0..A4
r23 = go_block('// round 23', 'binary.LittleEndian.PutUint64')
out.append('/-- Round 23 as written in the Go source: only the squeezed row (`A0..A4`) from `E0..E24`. -/')
out.append('def round23Go (e : Lanes) : Vector W 5 :=')
body = []
env = {'E%d' % k: 'e[%d]' % k for k in range(25)}
stmts = r23
ssa(stmts, env, body, 'j')
out += body
out.append('  #v[e0, e1, e2, e3, e4]\n')
out.append('''/-- One pair of chunks (64 bytes) to its digest, as the Go loop body computes it. -/
def nodeGo (l r : Nat → BitVec 8) : Vector (BitVec 8) 32 :=
  let e := round0Go (absorbGo l r)
  let e := loopGo 1 e 11
  let a := round23Go e
  Vector.ofFn fun j : Fin 32 =>
    match j.val / 8 with
    | 0 => st64 a[0] (j.val % 8)
    | 1 => st64 (~~~a[1]) (j.val % 8)
    | 2 => st64 (~~~a[2]) (j.val % 8)
    | _ => st64 a[3] (j.val % 8)

/-- `keccak256_1_generic(digests, chunks)`: `digests[i] = keccak256(chunks[2i] || chunks[2i+1])`. -/
def hashGo (chunks : Nat → Nat → BitVec 8) (i : Nat) : Vector (BitVec 8) 32 :=
  nodeGo (chunks (2 * i)) (chunks (2 * i + 1))

end Keccaktree.Generic
''')
open(os.path.join(HERE, 'Keccaktree', 'Generic.lean'), 'w').write('\n'.join(out))
print('written', sum(1 for _ in out))
